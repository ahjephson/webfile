#!/usr/bin/env python3
"""Collect installed runtime dependency licenses without embedding local paths."""

import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'THIRD_PARTY_NOTICES.txt'


def license_files(directory):
    files = sorted(path for path in directory.iterdir() if path.is_file() and
                   path.name.lower().startswith(('license', 'copying', 'copyright',
                                                 'notice', 'thirdpartynotice', 'patents')))
    if not files:
        raise RuntimeError(f'Missing license files for dependency {directory.name}')
    return files


def append_package(lines, name, version, directory):
    lines.extend(['', '=' * 72, f'{name} {version}', '=' * 72])
    for source in license_files(directory):
        text = source.read_text(encoding='utf-8-sig').strip()
        text = '\n'.join(line.rstrip() for line in text.splitlines())
        lines.extend(['', f'--- {source.name} ---', '', text])


def generate():
    lines = ['WebFile third-party notices', '',
             'Generated by scripts/generate-notices.py from installed Go modules',
             'and production npm dependencies, including the Tailwind CSS stylesheet.',
             'WebFile itself is licensed under MIT.',
             'Dependency licenses and notices are reproduced below.', '',
             '7-Zip, FFmpeg, PAM and operating-system packages are external runtime',
             'dependencies, not bundled executables in the WebFile release archive.']
    go_root = subprocess.check_output(['go', 'env', 'GOROOT'], cwd=ROOT / 'backend', text=True).strip()
    go_version = subprocess.check_output(['go', 'env', 'GOVERSION'], cwd=ROOT / 'backend', text=True).strip()
    append_package(lines, 'Go standard library', go_version, Path(go_root))
    used = set(subprocess.check_output([
        'go', 'list', '-tags=production,pam', '-deps', '-f',
        '{{if .Module}}{{.Module.Path}}{{end}}', './cmd/webfile',
    ], cwd=ROOT / 'backend', text=True).split())
    raw = subprocess.check_output(['go', 'list', '-m', '-json', 'all'], cwd=ROOT / 'backend', text=True)
    decoder = json.JSONDecoder()
    modules = []
    while raw.strip():
        module, end = decoder.raw_decode(raw.lstrip())
        raw = raw.lstrip()[end:]
        if not module.get('Main') and module['Path'] in used:
            modules.append(module)
    for module in sorted(modules, key=lambda item: item['Path']):
        append_package(lines, module['Path'], module['Version'], Path(module['Dir']))

    lock = json.loads((ROOT / 'web/package-lock.json').read_text())
    for relative, package in sorted(lock['packages'].items()):
        if not relative:
            continue
        if package.get('dev') and relative != 'node_modules/tailwindcss':
            continue
        directory = ROOT / 'web' / relative
        if package.get('optional') and not directory.exists():
            continue
        metadata = json.loads((directory / 'package.json').read_text())
        append_package(lines, metadata['name'], package['version'], directory)
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the checked-in notices are stale')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Third-party notices are stale; run python3 scripts/generate-notices.py')
        print('Third-party notices match installed runtime dependencies.')
    else:
        OUTPUT.write_text(content)
        print(f'Wrote {OUTPUT.name}')


if __name__ == '__main__':
    main()
