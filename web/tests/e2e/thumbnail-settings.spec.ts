import { expect, test } from '@playwright/test'

test('thumbnail settings persist, cancel edits safely and disable video requests', async ({ page }) => {
  let preferences: Record<string, unknown> = { view_mode: 'grid' }
  let thumbnailRequests = 0
  await page.route('**/api/preferences', async route => {
    if (route.request().method() === 'PUT') preferences = route.request().postDataJSON()
    await route.fulfill({ json: preferences })
  })
  await page.route('**/api/fs/dir**', route => route.fulfill({ json: { path: '/Files', single_root_path: '/Files', entries: [] } }))
  await page.route('**/api/fs/thumbnail?**', async route => { thumbnailRequests++; await route.fulfill({ status: 404 }) })
  await page.route('**/api/fs/thumbnails/queue', async route => { thumbnailRequests++; await route.fulfill({ json: { jobs: [] } }) })
  await page.goto('/#path=%2FFiles')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Settings', exact: true })
  await dialog.getByRole('spinbutton', { name: 'Concurrent video thumbnails', exact: true }).fill('4')
  await dialog.getByRole('spinbutton', { name: 'Threads per video process', exact: true }).fill('3')
  await dialog.getByRole('spinbutton', { name: 'Video thumbnail timeout', exact: true }).fill('600')
  await dialog.getByRole('spinbutton', { name: 'Maximum queued videos', exact: true }).fill('300')
  await dialog.getByRole('spinbutton', { name: 'Concurrent image thumbnails', exact: true }).fill('1')
  await dialog.getByRole('button', { name: 'Save settings' }).click()
  await expect(dialog).toBeHidden()
  await expect.poll(() => preferences.thumbnails).toMatchObject({ image_workers: 1, video_workers: 4, video_ffmpeg_threads: 3, video_timeout_seconds: 600, max_queued: 300 })
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await dialog.getByRole('spinbutton', { name: 'Concurrent video thumbnails', exact: true }).fill('8')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(dialog.getByRole('spinbutton', { name: 'Concurrent video thumbnails', exact: true })).toHaveValue('4')
  await dialog.getByRole('switch', { name: 'Video thumbnails', exact: true }).click()
  await dialog.getByRole('switch', { name: 'Image thumbnails', exact: true }).click()
  await dialog.getByRole('button', { name: 'Save settings' }).click()
  await expect(dialog).toBeHidden()
  await page.route('**/api/fs/dir**', route => route.fulfill({ json: { path: '/Files', single_root_path: '/Files', entries: ['movie.mp4', 'photo.jpg'].map(name => ({ name, path: '/Files/' + name, is_dir: false, size: 100, modified: '2000-01-01T00:00:00Z', mode: '-rw-r--r--' })) } }))
  await page.reload()
  await expect(page.locator('[data-file-entry]')).toHaveCount(2)
  await expect(page.locator('[data-file-thumbnail], [data-video-thumbnail]')).toHaveCount(0)
  expect(thumbnailRequests).toBe(0)
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(dialog.getByRole('switch', { name: 'Video thumbnails', exact: true })).not.toBeChecked()
  await expect(dialog.getByRole('switch', { name: 'Image thumbnails', exact: true })).not.toBeChecked()
})
