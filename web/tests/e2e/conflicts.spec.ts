import { expect, test } from '@playwright/test'
import { featureFixture } from './feature-fixture'

test('a delayed history response does not hide a newly waiting conflict', async ({ page }) => {
  const f = await featureFixture(page, 'history')
  await f.mkdir(`${f.path}/to`)
  await f.write(`${f.path}/item.txt`, 'source')
  await f.write(`${f.path}/to/item.txt`, 'destination')
  const history = await (await page.request.get('/api/fs/operations')).json()
  let release: () => void = () => {}
  const held = new Promise<void>(resolve => { release = resolve })
  let intercept: () => void = () => {}
  const intercepted = new Promise<void>(resolve => { intercept = resolve })
  await page.route('**/api/fs/operations', async route => {
    intercept()
    await held
    await route.fulfill({ json: history })
  }, { times: 1 })
  await page.reload()
  await intercepted
  await f.start('copy', [`${f.path}/item.txt`], `${f.path}/to`)
  const dialog = page.getByRole('dialog', { name: 'Resolve transfer conflict' })
  await expect(dialog).toBeVisible()
  release()
  await dialog.getByRole('button', { name: 'Skip', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect(await f.read(`${f.path}/to/item.txt`)).toBe('destination')
})

test('copy conflicts survive reconnect and require fresh review of changed destinations', async ({ page }) => {
  const f = await featureFixture(page, 'conflict')
  await f.mkdir(`${f.path}/from`)
  await f.mkdir(`${f.path}/to`)
  await f.write(`${f.path}/from/item.txt`, 'new content')
  await f.write(`${f.path}/to/item.txt`, 'original destination')
  const operation = await f.start('copy', [`${f.path}/from/item.txt`], `${f.path}/to`)
  const dialog = page.getByRole('dialog', { name: 'Resolve transfer conflict' })
  await expect(dialog).toBeVisible()
  await page.reload()
  await expect(dialog).toBeVisible()
  await f.write(`${f.path}/to/item.txt`, 'destination changed while reviewing')
  await dialog.getByRole('button', { name: 'Replace', exact: true }).click()
  await expect(dialog).toContainText('The source or destination changed')
  expect(await f.read(`${f.path}/to/item.txt`)).toBe('destination changed while reviewing')
  await dialog.getByRole('button', { name: 'Keep both', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => f.exists(`${f.path}/to/item (copy).txt`)).toBe(true)
  expect(await f.read(`${f.path}/to/item (copy).txt`)).toBe('new content')
  expect(await f.read(`${f.path}/from/item.txt`)).toBe('new content')
  await expect.poll(async () => (await (await page.request.get('/api/fs/operations')).json()).operations.find((task: { id: string }) => task.id === operation.id)?.state).toBe('completed')
})

test('folder merge retains skipped children and moves other files at narrow widths', async ({ page }) => {
  const f = await featureFixture(page, 'merge')
  await f.mkdir(`${f.path}/from`)
  await f.mkdir(`${f.path}/from/folder`)
  await f.mkdir(`${f.path}/to`)
  await f.mkdir(`${f.path}/to/folder`)
  await f.write(`${f.path}/from/folder/collision.txt`, 'source')
  await f.write(`${f.path}/from/folder/other.txt`, 'move me')
  await f.write(`${f.path}/to/folder/collision.txt`, 'destination')
  await page.setViewportSize({ width: 390, height: 844 })
  await f.start('move', [`${f.path}/from/folder`], `${f.path}/to`)
  const dialog = page.getByRole('dialog', { name: 'Resolve transfer conflict' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Replace', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Merge folders', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Replace', exact: true })).toBeVisible()
  await dialog.getByLabel('Apply to remaining conflicts of this type in this task').check()
  await dialog.getByRole('button', { name: 'Skip', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => f.exists(`${f.path}/to/folder/other.txt`)).toBe(true)
  expect(await f.read(`${f.path}/from/folder/collision.txt`)).toBe('source')
  expect(await f.exists(`${f.path}/from/folder/other.txt`)).toBe(false)
})

test('replacement is explicit and file-folder mismatches can be cancelled safely', async ({ page }) => {
  const f = await featureFixture(page, 'replace')
  await f.mkdir(`${f.path}/to`)
  await f.write(`${f.path}/item.txt`, 'replacement')
  await f.write(`${f.path}/to/item.txt`, 'original')
  await f.start('copy', [`${f.path}/item.txt`], `${f.path}/to`)
  const dialog = page.getByRole('dialog', { name: 'Resolve transfer conflict' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Replace', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => f.read(`${f.path}/to/item.txt`)).toBe('replacement')
  await f.mkdir(`${f.path}/from`)
  await f.mkdir(`${f.path}/from/item.txt`)
  const task = await f.start('move', [`${f.path}/from/item.txt`], `${f.path}/to`)
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Replace', exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: 'Merge folders', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Cancel task', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect.poll(async () => (await (await page.request.get('/api/fs/operations')).json()).operations.find((item: { id: string }) => item.id === task.id)?.state).toBe('cancelled')
  expect(await f.read(`${f.path}/to/item.txt`)).toBe('replacement')
})
